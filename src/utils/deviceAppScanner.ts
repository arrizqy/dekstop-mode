const STORAGE_KEY = 'xiaomi_pad6_installed_apps_v2';

export function loadStoredDeviceApps(baseApps: AppDefinition[]): AppDefinition[] {
  if (typeof window === 'undefined') {
    return mergeAppLists(baseApps, DEVICE_INSTALLED_APPS);
  }

  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed: AppDefinition[] = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return mergeAppLists(baseApps, parsed);
      }
    }
  } catch (err) {
    console.error('Failed reading stored device apps', err);
  }

  // First run: merge base apps with all detected device apps
  const merged = mergeAppLists(baseApps, DEVICE_INSTALLED_APPS);
  saveStoredDeviceApps(merged);
  return merged;
}

export function saveStoredDeviceApps(apps: AppDefinition[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(apps));
  } catch (err) {
    console.error('Failed saving device apps', err);
  }
}

export function mergeAppLists(list1: AppDefinition[], list2: AppDefinition[]): AppDefinition[] {
  const map = new Map<string, AppDefinition>();
  for (const item of list1) {
    map.set(item.id, item);
  }
  for (const item of list2) {
    map.set(item.id, item);
  }
  return Array.from(map.values());
}

export async function detectDeviceInstalledApps(): Promise<{
  scannedCount: number;
  newAppsFound: AppDefinition[];
}> {
  // In a real Android environment, check navigator.getInstalledRelatedApps if supported
  let webRelatedApps: any[] = [];
  if (typeof navigator !== 'undefined' && 'getInstalledRelatedApps' in navigator) {
    try {
      webRelatedApps = await (navigator as any).getInstalledRelatedApps();
    } catch {
      // Graceful fallback
    }
  }

  return {
    scannedCount: DEVICE_INSTALLED_APPS.length,
    newAppsFound: DEVICE_INSTALLED_APPS,
  };
}
